function parseMap(src) {
  const buf = [], gems = []; let start = { r: 0, c: 0 };
  src.forEach((line, r) => {
    let out = '';
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (ch === '⟨') {
        if (line[i + 1] === '⟩') { gems.push({ r, c: out.length }); i += 1; continue; }
        gems.push({ r, c: out.length }); out += line[i + 1]; i += 2; continue;
      }
      if (ch === '⟪') { start = { r, c: out.length }; out += line[i + 1]; i += 2; continue; }
      out += ch;
    }
    buf.push(out);
  });
  return { buf, gems, start };
}
function allowedFor(idx) { const s = new Set(); for (let i = 0; i <= idx; i++) LEVELS[i].learn.forEach(k => s.add(k)); return s; }

